import 'dart:convert';
import 'gst_invoice_format.dart';

/// Parsed result of a scanned Indian B2B GST e-Invoice QR Code.
///
/// In India, the Invoice Registration Portal (IRP / NIC) generates an e-invoice
/// QR code that contains a signed JWT payload with mandatory tax invoice attributes.
class GstEInvoiceQrResult {
  /// Whether the raw QR string is a valid, parseable Indian e-Invoice payload.
  final bool isValid;

  /// 15-character GSTIN of the supplier/seller.
  final String? sellerGstin;

  /// 15-character GSTIN of the buyer/recipient (or 'URP' if unregistered person).
  final String? buyerGstin;

  /// Invoice serial number (as issued by supplier).
  final String? documentNumber;

  /// Document type (`INV` for Tax Invoice, `CRN` for Credit Note, `DBN` for Debit Note).
  final GstDocumentType? documentType;

  /// Raw document type code string (e.g. 'INV').
  final String? rawDocumentType;

  /// Date of invoice issuance (e.g. '15/07/2024' or ISO date).
  final String? documentDate;

  /// Total invoice value (grand total inclusive of tax).
  final double? totalInvoiceValue;

  /// Number of line items on the invoice.
  final int? itemCount;

  /// Primary or major HSN / SAC code of items billed.
  final String? mainHsnCode;

  /// 64-character hexadecimal Invoice Reference Number (IRN) generated by NIC/IRP.
  final String? irn;

  /// Timestamp when the IRN was generated on the portal.
  final String? irnDate;

  /// Full parsed JSON claims map from the JWT payload.
  final Map<String, dynamic> rawPayload;

  /// Error explanation if the QR payload could not be parsed.
  final String? errorMessage;

  const GstEInvoiceQrResult({
    required this.isValid,
    this.sellerGstin,
    this.buyerGstin,
    this.documentNumber,
    this.documentType,
    this.rawDocumentType,
    this.documentDate,
    this.totalInvoiceValue,
    this.itemCount,
    this.mainHsnCode,
    this.irn,
    this.irnDate,
    this.rawPayload = const {},
    this.errorMessage,
  });

  @override
  String toString() {
    return 'GstEInvoiceQrResult(valid: $isValid, seller: $sellerGstin, docNo: $documentNumber, irn: ${irn != null ? '${irn!.substring(0, 10)}...' : null}, total: $totalInvoiceValue)';
  }
}

/// Offline Parser and Validator for Indian GST e-Invoice and B2C Dynamic QR codes.
///
/// Features:
/// - Pure Dart, zero-dependency offline decoding of NIC / IRP signed e-Invoice JWT payloads.
/// - Extraction of Seller/Buyer GSTIN, Document Number, IRN, Date, and Total Amount.
/// - 64-character SHA-256 IRN (Invoice Reference Number) validation.
/// - B2C Dynamic GST UPI QR parameter parser.
class BharatGstQr {
  static final RegExp _irnRegex = RegExp(r'^[0-9a-fA-F]{64}$');

  /// Validates whether a string is a syntactically valid 64-character hexadecimal
  /// Invoice Reference Number (IRN) mandated by the GST Council.
  static bool validateIrn(String? irn) {
    if (irn == null) return false;
    final cleaned = irn.trim();
    return _irnRegex.hasMatch(cleaned);
  }

  /// Parses the raw text content scanned from an Indian B2B GST e-Invoice QR code.
  ///
  /// The QR code printed on Indian e-invoices contains a JWT string signed by the
  /// Invoice Registration Portal (NIC / ClearTax / Cygnet / Iris).
  ///
  /// Example:
  /// ```dart
  /// final result = BharatGstQr.parseEInvoiceQr(scannedQrText);
  /// if (result.isValid) {
  ///   print('Seller: ${result.sellerGstin}');
  ///   print('Invoice: ${result.documentNumber}');
  ///   print('Total: ₹${result.totalInvoiceValue}');
  /// }
  /// ```
  static GstEInvoiceQrResult parseEInvoiceQr(String? rawQrText) {
    if (rawQrText == null || rawQrText.trim().isEmpty) {
      return const GstEInvoiceQrResult(
        isValid: false,
        errorMessage: 'Scanned QR content is empty',
      );
    }

    final trimmed = rawQrText.trim();

    try {
      Map<String, dynamic> payload;

      // 1. Try decoding as JWT (<header>.<payload>.<signature>)
      if (trimmed.contains('.')) {
        final parts = trimmed.split('.');
        if (parts.length >= 2) {
          final payloadBase64 = _normalizeBase64Url(parts[1]);
          final decodedJsonString =
              utf8.decode(base64Url.decode(payloadBase64));
          final dynamic parsed = jsonDecode(decodedJsonString);
          if (parsed is Map<String, dynamic>) {
            payload = parsed;
          } else {
            return const GstEInvoiceQrResult(
              isValid: false,
              errorMessage:
                  'Decoded JWT payload is not a valid JSON map structure',
            );
          }
        } else {
          return const GstEInvoiceQrResult(
            isValid: false,
            errorMessage: 'Malformed JWT structure in scanned QR code',
          );
        }
      } else if (trimmed.startsWith('{') && trimmed.endsWith('}')) {
        // Direct JSON string fallback
        final dynamic parsed = jsonDecode(trimmed);
        if (parsed is Map<String, dynamic>) {
          payload = parsed;
        } else {
          return const GstEInvoiceQrResult(
            isValid: false,
            errorMessage: 'Direct QR JSON is not a valid map',
          );
        }
      } else {
        return const GstEInvoiceQrResult(
          isValid: false,
          errorMessage:
              'QR content is neither a signed e-Invoice JWT nor a valid JSON document',
        );
      }

      // 2. Extract standard e-invoice fields with case-insensitive / alternate keys
      final sellerGstin = _extractString(
          payload, ['SellerGstin', 'sellerGstin', 'seller_gstin']);
      final buyerGstin =
          _extractString(payload, ['BuyerGstin', 'buyerGstin', 'buyer_gstin']);
      final docNo =
          _extractString(payload, ['DocNo', 'docNo', 'doc_no', 'invoice_no']);
      final rawDocTyp =
          _extractString(payload, ['DocTyp', 'docTyp', 'doc_type']);
      final docDt = _extractString(payload, ['DocDt', 'docDt', 'doc_date']);
      final totVal = _extractDouble(payload,
          ['TotInvVal', 'totInvVal', 'total_value', 'total_invoice_value']);
      final itemCnt =
          _extractInt(payload, ['ItemCnt', 'itemCnt', 'item_count']);
      final mainHsn = _extractString(
          payload, ['MainHsnCode', 'mainHsnCode', 'main_hsn', 'hsn_code']);
      final irn = _extractString(payload, ['Irn', 'irn']);
      final irnDt = _extractString(payload, ['IrnDt', 'irnDt', 'irn_date']);

      final docType = GstDocumentType.fromCode(rawDocTyp);

      if (sellerGstin == null && irn == null && docNo == null) {
        return GstEInvoiceQrResult(
          isValid: false,
          rawPayload: payload,
          errorMessage:
              'QR code payload does not contain required Indian e-Invoice fields (SellerGstin, Irn, or DocNo)',
        );
      }

      return GstEInvoiceQrResult(
        isValid: true,
        sellerGstin: sellerGstin,
        buyerGstin: buyerGstin,
        documentNumber: docNo,
        documentType: docType,
        rawDocumentType: rawDocTyp,
        documentDate: docDt,
        totalInvoiceValue: totVal,
        itemCount: itemCnt,
        mainHsnCode: mainHsn,
        irn: irn,
        irnDate: irnDt,
        rawPayload: payload,
      );
    } catch (e) {
      return GstEInvoiceQrResult(
        isValid: false,
        errorMessage: 'Failed to decode e-Invoice QR payload: $e',
      );
    }
  }

  /// Normalizes a Base64URL string by adjusting padding characters (`=`).
  static String _normalizeBase64Url(String input) {
    var normalized = input.replaceAll('-', '+').replaceAll('_', '/');
    final remainder = normalized.length % 4;
    if (remainder > 0) {
      normalized =
          normalized.padRight(normalized.length + (4 - remainder), '=');
    }
    return normalized;
  }

  static String? _extractString(
      Map<String, dynamic> map, List<String> candidateKeys) {
    for (final key in candidateKeys) {
      if (map.containsKey(key) && map[key] != null) {
        return map[key].toString();
      }
    }
    return null;
  }

  static double? _extractDouble(
      Map<String, dynamic> map, List<String> candidateKeys) {
    for (final key in candidateKeys) {
      if (map.containsKey(key) && map[key] != null) {
        final val = map[key];
        if (val is num) return val.toDouble();
        return double.tryParse(val.toString());
      }
    }
    return null;
  }

  static int? _extractInt(
      Map<String, dynamic> map, List<String> candidateKeys) {
    for (final key in candidateKeys) {
      if (map.containsKey(key) && map[key] != null) {
        final val = map[key];
        if (val is int) return val;
        return int.tryParse(val.toString());
      }
    }
    return null;
  }
}
